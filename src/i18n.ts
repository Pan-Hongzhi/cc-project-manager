import { computed, ref } from "vue";
import { dateEnUS, dateZhCN, enUS, zhCN } from "naive-ui";

export type Locale = "zh" | "en";
const STORAGE_KEY = "ccpm.locale";

function initial(): Locale {
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    if (v === "zh" || v === "en") return v;
  } catch {
    /* localStorage 不可用时用默认值 */
  }
  return "zh";
}

export const locale = ref<Locale>(initial());

export function setLocale(l: Locale) {
  locale.value = l;
  try {
    localStorage.setItem(STORAGE_KEY, l);
  } catch {
    /* ignore */
  }
}

/** Naive UI 组件自身的文案（分页、空态等）跟随语言 */
export const naiveLocale = computed(() => (locale.value === "zh" ? zhCN : enUS));
export const naiveDateLocale = computed(() => (locale.value === "zh" ? dateZhCN : dateEnUS));

