const dicts: Record<Locale, Dict> = { zh, en };

/** 取文案；`{name}` 占位符用 params 填充。缺失的 key 原样返回，便于发现遗漏。 */
export function t(key: string, params?: Record<string, string | number>): string {
  const s = dicts[locale.value][key] ?? dicts.zh[key] ?? key;
  if (!params) return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
}

/** 后端命令返回的错误统一为 `err.<code>|arg0|arg1` 形式，这里翻译成当前语言 */
export function translateError(e: unknown): string {
  const raw = String(e);
  if (!raw.startsWith("err.")) return raw;
  const [code, ...args] = raw.split("|");
  if (!(code in dicts.zh)) return raw;
  const params: Record<string, string> = {};
  args.forEach((a, i) => (params[String(i)] = a));
  return t(code, params);
}
